// Gibt das SVG als String zurück (für innerHTML und Vorlagen). Das String-
// Objekt trägt eine Markierung, damit h() es als HTML statt als Text einsetzt.
export function icon(name, cls = '') {
  const p = P[name] || P.file;
  const s = new String(`<svg class="icon ${cls}" viewBox="0 0 24 24" aria-hidden="true">${p}</svg>`);
  s.__html = true;
  return s;
}

export function hasIcon(name) { return !!P[name]; }
